/**
 * Builds the PWA icons and web app manifests from the logo and the colour
 * tokens (packages/ui/src/tokens.css), so no colour is typed by hand:
 *   node scripts/build-icons.mjs
 * Renders with Playwright's Chromium (preinstalled). Outputs are committed:
 *   public/icons/{icon,maskable}-{192,512}.png, apple-touch-icon.png, badge-96.png
 *   public/manifest.webmanifest (app, starts on /accueil)
 *   public/terrain.webmanifest (tournament pages: no start_url, so a page added
 *   to the home screen reopens on that page — needed on iPhone for push)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = readFileSync(join(root, "../../packages/ui/src/tokens.css"), "utf8");

/** n-th declaration of a token (0 = light :root, 1 = dark theme). */
function token(name, nth = 0) {
  const all = [...tokens.matchAll(new RegExp(`--os-${name}:\\s*(#[0-9a-fA-F]{3,8})`, "g"))].map((m) => m[1]);
  if (!all[nth]) throw new Error(`token --os-${name} #${nth} not found`);
  return all[nth];
}

const COLORS = {
  background: token("bg"), // --os-bg (light): manifest background / splash screen
  plate: token("ink"), // --os-ink (light, « Cobalt »): icon plate
  bar: token("bg"), // --os-bg (light): first bar of the mark
  accent: token("accent", 1), // --os-accent (dark theme): second bar, readable on cobalt
};

// Same paths as LogoMark in packages/ui/src/logo.tsx (viewBox 0 0 44 44).
const MARK = (a, b) => `<path d="M10 6 H24 L16 38 H2 Z" fill="${a}"/><path d="M28 6 H42 L34 38 H20 Z" fill="${b}"/>`;

/** scale = share of the icon taken by the mark; radius = corner rounding (0 = full bleed). */
function svg({ size, scale, radius, plate = COLORS.plate, bar = COLORS.bar, accent = COLORS.accent }) {
  const mark = size * scale;
  const offset = (size - mark) / 2;
  const plateRect = plate ? `<rect width="${size}" height="${size}" rx="${radius * size}" fill="${plate}"/>` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">${plateRect}<g transform="translate(${offset} ${offset}) scale(${mark / 44})">${MARK(bar, accent)}</g></svg>`;
}

const ICONS = [
  { file: "icon-192.png", size: 192, scale: 0.68, radius: 0.22 },
  { file: "icon-512.png", size: 512, scale: 0.68, radius: 0.22 },
  // Maskable: full bleed, mark inside the 80 % safe circle.
  { file: "maskable-192.png", size: 192, scale: 0.5, radius: 0 },
  { file: "maskable-512.png", size: 512, scale: 0.5, radius: 0 },
  // iOS rounds the corners itself.
  { file: "apple-touch-icon.png", size: 180, scale: 0.62, radius: 0 },
  // Android status bar badge: only the alpha channel counts (--os-surface, white, on transparent).
  { file: "badge-96.png", size: 96, scale: 0.86, radius: 0, plate: null, bar: token("surface"), accent: token("surface") },
];

const outDir = join(root, "public/icons");
mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  for (const icon of ICONS) {
    await page.setViewportSize({ width: icon.size, height: icon.size });
    await page.setContent(`<html><body style="margin:0;background:transparent">${svg(icon)}</body></html>`);
    await page.locator("svg").screenshot({ path: join(outDir, icon.file), omitBackground: true });
    console.log(`icons/${icon.file}`);
  }
} finally {
  await browser.close();
}

