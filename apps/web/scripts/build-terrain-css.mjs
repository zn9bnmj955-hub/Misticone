// Builds the CSS of the terrain pages: design tokens + terrain.css, minified,
// as a TypeScript string module. Runs before dev, build and tests.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = readFileSync(join(here, "../../../packages/ui/src/tokens.css"), "utf8");
const terrain = readFileSync(join(here, "../src/terrain/terrain.css"), "utf8");
const minify = (css) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{};:,>])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
const out = `// GENERATED by scripts/build-terrain-css.mjs from packages/ui/src/tokens.css and src/terrain/terrain.css.\nexport const TERRAIN_CSS = ${JSON.stringify(minify(tokens + "\n" + terrain))};\n`;
writeFileSync(join(here, "../src/terrain/styles.generated.ts"), out);
console.log(`terrain css: ${out.length} bytes`);
