import type { Metadata, Viewport } from "next";
import localFont from "next/font/local";
import { InlineScript } from "@/components/ui/InlineScript";
import { getMessages } from "@/i18n";
import { env } from "@/lib/env";
import { SPORT_COOKIE, offeredSportSlugs } from "@/lib/prefs";
import "./globals.css";

// Lightened by scripts/subset-fonts.py: upright text at normal width,
// italic display type at 50–75 % width (80 KB in all instead of 210 KB).
const saira = localFont({
  src: [
    { path: "../fonts/saira-latin-normal.woff2", style: "normal", weight: "400 900" },
    { path: "../fonts/saira-latin-italic.woff2", style: "italic", weight: "700 900" },
  ],
  variable: "--font-saira",
  display: "swap",
  // Lets the browser drive the italic width axis (font-stretch 50–75 %).
  declarations: [{ prop: "font-stretch", value: "50% 100%" }],
});

const m = getMessages();

export const metadata: Metadata = {
  metadataBase: new URL(env.siteUrl),
  title: { default: `${m.meta.title} · ${m.meta.tagline}`, template: `%s · ${m.meta.title}` },
  description: m.meta.description,
  applicationName: m.meta.title,
  formatDetection: { telephone: false },
  // Installable app (PWA): files generated by scripts/build-icons.mjs.
  manifest: "/manifest.webmanifest",
  appleWebApp: { capable: true, title: m.meta.title, statusBarStyle: "default" },
  icons: {
    icon: [{ url: "/icons/icon-192.png", sizes: "192x192", type: "image/png" }],
    apple: [{ url: "/icons/apple-touch-icon.png", sizes: "180x180", type: "image/png" }],
  },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
  // Same values as --os-bg in packages/ui/src/tokens.css (light, dark).
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#f3f5fa" },
    { media: "(prefers-color-scheme: dark)", color: "#04060c" },
  ],
};

// Applies the remembered theme and sport accent before the first paint
// (only for a sport still offered: an old os_sport=football cookie is ignored).
const BOOT = `(function(){try{var d=document.documentElement;var t=localStorage.getItem("os_theme");if(t==="light"||t==="dark")d.setAttribute("data-theme",t);var m=document.cookie.match(/(?:^|; )${SPORT_COOKIE}=([^;]+)/);if(m&&${JSON.stringify(offeredSportSlugs())}.indexOf(m[1])>=0)d.setAttribute("data-sport",m[1]);}catch(e){}})();`;

export default function RootLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  return (
    <html lang="fr" className={saira.variable} suppressHydrationWarning>
      <head>
        <InlineScript html={BOOT} />
      </head>
      <body className="min-h-dvh">{children}</body>
    </html>
  );
}
